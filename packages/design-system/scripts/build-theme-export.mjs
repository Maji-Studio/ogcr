// Emits dist/theme.css — the `@majistudio/ogcr-design-system/theme` export.
//
// WHY IT EXISTS. dist/styles.css is PRECOMPILED: the DS's Tailwind ran once, at publish time, so
// only the utilities pinned in src/styles/safelist.css exist. That is enough for the documented
// surface, but it can never be complete — a consumer writing `group-hover:bg-surface-progress`,
// `md:gap-120`, `data-[state=open]:border-border-strong` or `bg-surface-progress/60` needs a
// COMPILER, not a bigger safelist. Shipping the token definitions as importable Tailwind source
// gives them one:
//
//     @import "tailwindcss";
//     @import "@majistudio/ogcr-design-system/theme";     /* ← this file */
//
// Their own Tailwind now knows every DS token and generates any utility × any variant natively,
// from their own source scan. The safelist stays as the zero-config fallback for apps that only
// import the precompiled styles.css.
//
// SELF-CONTAINED BY CONSTRUCTION. The file is a concatenation of the two token sources
// (palette.css, then theme.css) rather than a file that `@import`s them, because a published
// stylesheet cannot carry build-relative import paths. check-dist.mjs asserts the emitted file
// contains no `@import` at all, so this stays true if someone later adds one upstream.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const styles = path.join(root, 'src', 'styles');
const outFile = path.join(root, 'dist', 'theme.css');

// Order matters: the palette's `--ds-*` custom properties must be declared before the `@theme`
// block that references them (theme.css's color tokens are all `var(--ds-*)`).
const SOURCES = ['palette.css', 'theme.css'];

const HEADER = `/* ============================================================
 * @majistudio/ogcr-design-system/theme
 *
 * GENERATED by scripts/build-theme-export.mjs — do not edit.
 * Source: src/styles/${SOURCES.join(' + src/styles/')}
 *
 * Import this into your OWN Tailwind v4 build to teach your compiler
 * the OGCR token scales, so it generates any DS utility with any
 * variant on demand:
 *
 *     @import "tailwindcss";
 *     @import "@majistudio/ogcr-design-system/theme";
 *
 * That is the complete alternative to the precompiled
 * "@majistudio/ogcr-design-system/styles.css", which ships a fixed
 * utility surface (see src/styles/safelist.css). Most apps want BOTH:
 * styles.css for the reset + the DS components' own compiled classes,
 * this file so their own markup can use DS tokens freely. The token
 * values are identical, so the duplicate \`:root\` declarations are
 * harmless.
 *
 * NOTE: this pins \`--spacing: 1px\` in your build, which is the point —
 * it puts your own numeric spacing utilities on the DS px scale
 * (p-16 = 16px). See the note on --spacing in the theme block below.
 * ============================================================ */

`;

const parts = SOURCES.map((name) => {
  const file = path.join(styles, name);
  if (!fs.existsSync(file)) {
    console.error(`\n✗ build-theme-export — src/styles/${name} not found.\n`);
    process.exit(1);
  }
  return `/* ---------- src/styles/${name} ---------- */\n${fs.readFileSync(file, 'utf8')}`;
});

const out = HEADER + parts.join('\n');

if (/^\s*@import\b/m.test(out)) {
  console.error(
    `\n✗ build-theme-export — the concatenated theme export contains an @import. A published ` +
      `stylesheet cannot resolve build-relative paths; inline the dependency into a SOURCES entry.\n`,
  );
  process.exit(1);
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(
  `build-theme-export: dist/theme.css ← ${SOURCES.join(' + ')} ` +
    `(${(out.length / 1024).toFixed(1)} kB, self-contained).`,
);
